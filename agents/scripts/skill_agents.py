#!/usr/bin/env python3
"""Builds the skill agents (MattPocock/, JesseVincent/) from the skills in skills_updated/, or checks they are current.

    python3 agents/scripts/skill_agents.py           # check: agent files and file lists match skills_updated/
    python3 agents/scripts/skill_agents.py --write   # regenerate them after skills_updated/ changes

For each agent this writes two things: the skills table in its .agent.md (between the skills:begin and skills:end
markers), and its files.txt, the list of files that install.sh and install.ps1 download. Each files.txt line is
`<path in this repository>\t<path under the install folder>\t<x if executable>`, where the install folder is a
project's .github/ or ~/.copilot/. The skills go to agent-skills/<slug>/<skill>/, outside the folders VS Code loads
skills from, so that only this agent uses them. Each agent file needs a name and a description and must leave out
tools, model and agents, so that it keeps the default agent's tools, model and subagents. Standard library only.
"""
import os
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
AGENTS = REPO / "agents"
sys.dont_write_bytecode = True
sys.path.insert(0, str(REPO / "skills_updated" / "scripts"))
from skills_index import front_matter  # noqa: E402

BEGIN = "<!-- skills:begin (generated by agents/scripts/skill_agents.py, do not edit by hand) -->"
END = "<!-- skills:end -->"

# folder: agents/<folder>/; slug: agent-skills/<slug>/; groups: folders of skills_updated/ whose skills it gets.
SKILL_AGENTS = [
    {
        "folder": "MattPocock",
        "agent": "matt-pocock.agent.md",
        "slug": "matt-pocock",
        # The two collections Matt Pocock's own plugin installs; misc/ and in-progress/ (beta) are left out.
        "groups": ["skills_updated/matt-pocock/engineering", "skills_updated/matt-pocock/productivity"],
        "license": "skills_updated/matt-pocock/LICENSE",
    },
    {
        "folder": "JesseVincent",
        "agent": "jesse-vincent.agent.md",
        "slug": "superpowers",
        "groups": ["skills_updated/superpowers"],
        "license": "skills_updated/superpowers/LICENSE",
    },
]


def skills(config):
    """(name, folder, front matter) of every skill in the agent's groups, sorted by name."""
    found = {}
    for group in config["groups"]:
        for path in sorted((REPO / group).glob("*/SKILL.md")):
            fields = front_matter(path)
            name = fields.get("name", "")
            if name != path.parent.name or not fields.get("description"):
                raise ValueError(f"{path}: needs a description and a name equal to its folder name")
            if name in found:
                raise ValueError(f"{path}: two skills named {name}")
            found[name] = (path.parent, fields)
    if not found:
        raise ValueError(f"{config['folder']}: no skills")
    return sorted((name, folder, fields) for name, (folder, fields) in found.items())


def table(config):
    out = ["| Skill | Use it when | File |", "|-------|-------------|------|"]
    for name, _, fields in skills(config):
        description = fields["description"].replace("|", "\\|")
        if fields.get("disable-model-invocation") == "true":
            description = "**On request.** " + description
        out.append(f"| `{name}` | {description} | `{name}/SKILL.md` |")
    return "\n".join(out) + "\n"


def files(config):
    def line(source, target):
        flag = "x" if os.access(source, os.X_OK) else ""
        return f"{source.relative_to(REPO).as_posix()}\t{target}\t{flag}"

    agent = AGENTS / config["folder"] / ".github" / "agents" / config["agent"]
    base = f"agent-skills/{config['slug']}"
    out = [line(agent, f"agents/{config['agent']}"), line(REPO / config["license"], f"{base}/LICENSE")]
    for name, folder, _ in skills(config):
        for path in sorted(p for p in folder.rglob("*") if p.is_file()):
            out.append(line(path, f"{base}/{name}/{path.relative_to(folder).as_posix()}"))
    return "\n".join(out) + "\n"


def main():
    write, stale = "--write" in sys.argv, []
    for config in SKILL_AGENTS:
        agent = AGENTS / config["folder"] / ".github" / "agents" / config["agent"]
        meta = front_matter(agent)
        if not meta.get("name") or not meta.get("description"):
            sys.exit(f"{agent.relative_to(REPO)}: front matter needs a name and a description")
        if {"tools", "model", "agents"} & meta.keys():
            sys.exit(f"{agent.relative_to(REPO)}: leave tools, model and agents out, as the default agent does")
        text = agent.read_text(encoding="utf-8")
        start, end = text.index(BEGIN) + len(BEGIN), text.index(END)
        outputs = {agent: text[:start] + "\n" + table(config) + text[end:]}
        outputs[AGENTS / config["folder"] / "files.txt"] = files(config)
        for path, content in outputs.items():
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current == content:
                continue
            if write:
                path.write_text(content, encoding="utf-8")
                print(f"{path.relative_to(REPO)} updated")
            else:
                stale.append(str(path.relative_to(REPO)))
        if not write:
            print(f"{config['folder']}: {len(skills(config))} skills")
    if stale:
        sys.exit("Out of date: " + ", ".join(stale) + ". Run `python3 agents/scripts/skill_agents.py --write`.")


if __name__ == "__main__":
    main()
