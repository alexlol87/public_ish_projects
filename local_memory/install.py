#!/usr/bin/env python3
"""Installs Local Memory for GitHub Copilot into your Copilot home (~/.copilot, or $COPILOT_HOME):
  local-memory/mem.py                        the memory tool (Python 3 standard library only)
  hooks/local-memory.json                    session-start context and the prompt/failure log for /alx-reflect
  skills/alx-remember, skills/alx-reflect    the skills the agent uses
  skills/alx-disable-memory, alx-enable-memory   pause and resume Local Memory (user-invoked only)
  instructions/local-memory.instructions.md  your user memory, loaded in every session (regenerated by mem.py)
Your saved memory in local-memory/ is never overwritten. Run it again to update.

Usage:
  python3 install.py              install or update (Windows: py install.py)
  python3 install.py --no-hooks   skip the hooks (memory still works through the instructions file and `mem.py recall`)
  python3 install.py --uninstall  remove everything above except your saved memory
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))  # mem.py sits next to this file; it holds the shared quoting helper
from mem import command_prefix, ps_quote  # noqa: E402
SKILLS = ("alx-remember", "alx-reflect", "alx-disable-memory", "alx-enable-memory")
OLD_SKILLS = ("remember", "reflect")  # unprefixed names from earlier installs


def copilot_home() -> Path:
    return Path(os.environ.get("COPILOT_HOME") or Path.home() / ".copilot")


def render(text: str, shell: str, python: str, mem: str) -> str:
    return text.replace("__CMD__", command_prefix(shell, python, mem))


def hooks_config(python: str, mem: str) -> dict:
    # Load the template as JSON and fill in each shell's command, so escaping is JSON's job.
    data = json.loads((HERE / "hooks" / "local-memory.json").read_text(encoding="utf-8"))
    for entries in data["hooks"].values():
        for entry in entries:
            for shell in ("bash", "powershell"):
                entry[shell] = render(entry[shell], shell, python, mem)
    return data


def install(home: Path, hooks: bool) -> None:
    python = sys.executable  # the interpreter running this installer, so hooks never depend on a bare `python3`
    mem_dir = home / "local-memory"
    mem = mem_dir / "mem.py"
    mem_dir.mkdir(parents=True, exist_ok=True)
    shutil.rmtree(mem_dir / "paused", ignore_errors=True)  # installing switches Local Memory back on
    shutil.copyfile(HERE / "mem.py", mem)
    mem.chmod(0o755)
    print(f"ok    tool -> {mem}")

    # Skills run in the agent's terminal: PowerShell on Windows, POSIX shell elsewhere.
    shell = "powershell" if os.name == "nt" else "bash"
    for skill in OLD_SKILLS:
        shutil.rmtree(home / "skills" / skill, ignore_errors=True)
    for skill in SKILLS:
        target = home / "skills" / skill
        shutil.rmtree(target, ignore_errors=True)
        target.mkdir(parents=True)
        text = (HERE / "skills" / skill / "SKILL.md").read_text(encoding="utf-8")
        (target / "SKILL.md").write_text(render(text, shell, python, str(mem)), encoding="utf-8")
    print(f"ok    skills: {', '.join(SKILLS)} -> {home / 'skills'}")

    hooks_file = home / "hooks" / "local-memory.json"
    if hooks:
        hooks_file.parent.mkdir(parents=True, exist_ok=True)
        config = hooks_config(python, str(mem))
        hooks_file.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
        print(f"ok    hooks -> {hooks_file}")
    else:
        hooks_file.unlink(missing_ok=True)
        print("skip  hooks (--no-hooks)")

    subprocess.run([python, str(mem), "sync"], check=True, stdout=subprocess.DEVNULL)
    print(f"ok    instructions -> {home / 'instructions' / 'local-memory.instructions.md'}")
    print("Installed. Start a new Copilot session, then check Chat: Open Customizations (skills, hooks, instructions).")


def uninstall(home: Path) -> None:
    (home / "local-memory" / "mem.py").unlink(missing_ok=True)
    (home / "hooks" / "local-memory.json").unlink(missing_ok=True)
    (home / "instructions" / "local-memory.instructions.md").unlink(missing_ok=True)
    for skill in SKILLS + OLD_SKILLS:
        shutil.rmtree(home / "skills" / skill, ignore_errors=True)
    print(f"Removed Local Memory. Your saved memory is still in {home / 'local-memory'}; "
          "delete that folder to remove it too.")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Install Local Memory for GitHub Copilot.")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--no-hooks", action="store_true", help="skip the hooks")
    group.add_argument("--uninstall", action="store_true", help="remove everything except your saved memory")
    args = parser.parse_args(argv)
    if args.uninstall:
        uninstall(copilot_home())
    else:
        install(copilot_home(), hooks=not args.no_hooks)
    return 0


if __name__ == "__main__":
    sys.exit(main())
