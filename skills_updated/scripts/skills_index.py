#!/usr/bin/env python3
"""Builds the skills table in skills_updated/README.md from each SKILL.md's front matter, or checks it is current.

    python3 scripts/skills_index.py           # check: every skill has a name and description, README is up to date
    python3 scripts/skills_index.py --write   # regenerate the table after adding or updating skills

Standard library only. The front matter parser understands what skills use: `key: value` and folded/literal block
scalars (`key: >` / `key: |`) and plain scalars that start on the next line (`key:`), with indented continuation lines.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
BEGIN = "<!-- skills:begin (generated by scripts/skills_index.py, do not edit by hand) -->"
END = "<!-- skills:end -->"

# Section title per directory (relative to skills_updated/), in README order.
GROUPS = [
    ("matt-pocock/engineering", "Matt Pocock: engineering"),
    ("matt-pocock/productivity", "Matt Pocock: productivity"),
    ("matt-pocock/misc", "Matt Pocock: misc (kept around, rarely used)"),
    ("matt-pocock/in-progress", "Matt Pocock: in progress (beta, may change or disappear)"),
    ("superpowers", "Superpowers (obra)"),
    ("caveman", "Caveman"),
    ("ponytail", "Ponytail"),
    ("shadcn", "shadcn"),
    ("cursor", "Cursor"),
    ("humanlayer", "HumanLayer (visual-pr, show-me)"),
    ("popular/vercel", "New: Vercel (find-skills, agent-browser, React and web design)"),
    ("popular/anthropic", "New: Anthropic (official skills)"),
    ("popular/karpathy", "New: Karpathy guidelines"),
    ("popular/addy-osmani", "New: Addy Osmani's agent skills"),
    ("popular/ui-ux-pro-max", "New: UI UX Pro Max"),
    ("popular/taste-skill", "New: Taste Skill"),
    ("popular/impeccable", "New: Impeccable"),
]


def unquote(value):
    """YAML scalar quoting: "double" (backslash escapes) or 'single' ('' is a quote)."""
    if len(value) >= 2 and value[0] == value[-1] == '"':
        return value[1:-1].replace('\\"', '"').replace("\\\\", "\\")
    if len(value) >= 2 and value[0] == value[-1] == "'":
        return value[1:-1].replace("''", "'")
    return value


def front_matter(path):
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{path}: no front matter")
    fields, key, block = {}, None, None
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if block is not None and (line.startswith((" ", "\t")) or not line.strip()):
            block.append(line.strip())
            continue
        if block is not None:
            fields[key] = " ".join(part for part in block if part)
            block = None
        if ":" in line and not line.startswith((" ", "\t")):
            key, value = line.split(":", 1)
            key, value = key.strip(), value.strip()
            if value in ("", ">", "|", ">-", "|-", ">+", "|+"):
                block = []
            else:
                fields[key] = unquote(value)
    else:
        raise ValueError(f"{path}: unterminated front matter")
    if block is not None:
        fields[key] = " ".join(part for part in block if part)
    return fields


def table():
    out, seen = [], set()
    for directory, title in GROUPS:
        skills = sorted((ROOT / directory).rglob("SKILL.md"))
        if not skills:
            raise ValueError(f"{directory}: no skills")
        out += [f"### {title}", "", "| Skill | Description |", "|-------|-------------|"]
        for path in skills:
            fields = front_matter(path)
            name, description = fields.get("name", ""), fields.get("description", "")
            if not name or not description:
                raise ValueError(f"{path}: front matter needs a name and a description")
            seen.add(path)
            link = path.relative_to(ROOT).as_posix()
            cell = description.replace("|", "\\|")
            out.append(f"| [`{name}`]({link}) | {cell} |")
        out.append("")
    missing = set(ROOT.rglob("SKILL.md")) - seen
    if missing:
        raise ValueError("skills outside the listed groups: " + ", ".join(sorted(str(p) for p in missing)))
    return "\n".join(out).rstrip() + "\n"


def main():
    text = README.read_text(encoding="utf-8")
    start, end = text.index(BEGIN) + len(BEGIN), text.index(END)
    updated = text[:start] + "\n" + table() + text[end:]
    if "--write" in sys.argv:
        README.write_text(updated, encoding="utf-8")
        print("README.md updated")
    elif updated != text:
        sys.exit("README.md is out of date: run `python3 scripts/skills_index.py --write` in skills_updated/")
    else:
        print(f"OK: {len(list(ROOT.rglob('SKILL.md')))} skills, README up to date")


if __name__ == "__main__":
    main()
